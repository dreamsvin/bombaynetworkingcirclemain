/**
 * Turns content/seed.ts into supabase/seed.sql, so the database and the no-DB fallback start identical.
 * Run: npm run db:seed-sql   (then apply with `supabase db reset` or psql -f supabase/seed.sql)
 * Placeholder rows are inserted with is_published = false, so RLS keeps them off the public site.
 */
import { writeFileSync } from "node:fs";
import { CHAPTERS, EVENTS, MEMBERS, SPONSORS, STORIES, TESTIMONIALS } from "../content/seed";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table: string, rows: object[]) {
  if (!rows.length) return `-- ${table}: no rows yet\n`;
  const cols = Object.keys(rows[0]).filter((c) => c !== "created_at" && c !== "updated_at");
  const values = rows.map((r) => `  (${cols.map((c) => lit((r as Record<string, unknown>)[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (id) do nothing;\n`;
}

const sql = [
  "-- Generated by scripts/build-seed-sql.ts from content/seed.ts. Do not edit by hand.",
  "-- Rows containing [PLACEHOLDER — replace before launch] are unpublished and must be replaced before launch.",
  "begin;",
  insert("chapters", CHAPTERS),
  insert("events", EVENTS),
  insert("members", MEMBERS),
  insert("stories", STORIES),
  insert("testimonials", TESTIMONIALS),
  insert("sponsors", SPONSORS),
  "commit;",
  "",
].join("\n");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
