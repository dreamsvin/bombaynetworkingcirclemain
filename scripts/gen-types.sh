#!/usr/bin/env bash
# Regenerate lib/supabase/database.types.ts from the schema. Never hand-write row types.
#
#   Hosted project:  SUPABASE_PROJECT_ID=xxxx npm run db:types      (needs `npx supabase login` once)
#   Any Postgres:    DB_URL=postgresql://... npm run db:types        (uses @supabase/postgres-meta, the CLI's generator)
set -euo pipefail
OUT="lib/supabase/database.types.ts"
HEADER=$'// Generated by Supabase type generation from supabase/migrations.\n// Do not edit by hand — run `npm run db:types`.\n'
if [[ -n "${SUPABASE_PROJECT_ID:-}" ]]; then
  BODY=$(npx -y supabase@latest gen types typescript --project-id "$SUPABASE_PROJECT_ID" --schema public)
elif [[ -n "${DB_URL:-}" ]]; then
  BODY=$(PG_META_DB_URL="$DB_URL" PG_META_GENERATE_TYPES=typescript PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public \
    npx -y @supabase/postgres-meta@0.100.1 2>/dev/null || \
    PG_META_DB_URL="$DB_URL" PG_META_GENERATE_TYPES=typescript PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public \
    node "$(npm root -g)/@supabase/postgres-meta/dist/server/server.js")
else
  echo "Set SUPABASE_PROJECT_ID or DB_URL" >&2; exit 1
fi
printf '%s\n%s\n' "$HEADER" "$BODY" > "$OUT"
echo "wrote $OUT"
